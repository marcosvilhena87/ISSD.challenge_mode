package.path="./lua/?.lua;./lua/?/init.lua;"..package.path
local E=require("challenge.dribble_entry_target_v7")
local function s(f,x,y) return {frame=f,px=x,py=y} end
local a=E.new()
E.choose(a,s(10,600,300))
assert(E.drain(a)[1].kind=="entry_target_activated")
E.collected(a,s(11,742,331))
assert(E.drain(a)[1].kind=="collected_before_fallback")
local b=E.new()
E.choose(b,s(10,600,300));E.drain(b)
assert(E.choose(b,s(20,744,329))==nil)
local ev=E.drain(b)
assert(ev[1].kind=="candidate_reached" and ev[2].kind=="fallback_started")
E.collected(b,s(21,750,329))
assert(E.drain(b)[1].kind=="collected_after_fallback")
local c=E.new()
E.choose(c,s(10,500,300));E.drain(c)
E.choose(c,s(180,500,300))
assert(E.drain(c)[1].cause=="timeout")
